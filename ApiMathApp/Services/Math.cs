namespace Class207
{
    public class Math
    {
        public int Sum (int num1, int num2)
        {
            return num1 + num2;
        }
        public int Sum(int num1, int num2, int num3)
        {
            return num1 + num2 + num3;
        }
        public int Sub(int num1, int num2)
        {
            return num1 - num2;
        }
        public int Sub(int num1, int num2, int num3)
        {
            return num1 - num2 - num3;
        }
        public int Mul(int num1, int num2)
        {  
            return num1 * num2; 
        }
    }
}
